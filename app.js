function buildSpreads() {
  const pages = [
    { label: "Cover", render: coverPage },
    { label: "Cover", render: insideCoverPage },
    { label: "Contents", render: contentsPage },
    { label: "Contents", render: overviewPage },
  ];

  categoryOrder.forEach((category) => {
    const categoryCourses = courses.filter((course) => course.category === category);
    pages.push({
      label: category,
      category,
      isSectionStart: true,
      render: () => sectionPage(category, categoryCourses),
    });
    categoryCourses.forEach((course, index) => {
      pages.push({
        label: category,
        category,
        courseId: course.id,
        courseTitle: course.title,
        render: () => coursePage(course, index + 1),
      });
    });
    if (pages.length % 2 === 1) {
      pages.push({ label: category, category, render: blankPage });
    }
  });

  pages.push({ label: "Closing", render: closingPage });

  const paired = [];
  for (let index = 0; index < pages.length; index += 2) {
    paired.push({
      label: pages[index].label,
      left: pages[index].render,
      right: pages[index + 1]?.render || blankPage,
      leftMeta: pages[index],
      rightMeta: pages[index + 1],
    });
  }
  return paired;
}

